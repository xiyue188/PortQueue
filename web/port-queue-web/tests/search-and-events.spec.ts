test('动态遍历完整历史，标题固定，暂停和关联预约可用', async ({ page, request }) => {
  const summary = await (await request.get('/api/overview')).json()
  await page.goto('/')
  await expect(page.locator('.recent-events li')).toHaveCount(12)
  const viewport = page.getByRole('region', { name: '港口动态记录' })
  const heading = await page.locator('.events-heading').boundingBox()
  await page.mouse.move(0, 0)
  await expect.poll(() => viewport.evaluate(element => element.scrollTop), { timeout: 7000 }).toBeGreaterThan(15)
  expect(await page.locator('.events-heading').boundingBox()).toEqual(heading)
  await page.getByRole('button', { name: '暂停动态滚动' }).click()
  const pausedTop = await viewport.evaluate(element => element.scrollTop)
  await page.waitForTimeout(500)
  expect(await viewport.evaluate(element => element.scrollTop)).toBe(pausedTop)
  const seen: string[] = []
  for (let batch = 1; batch <= Math.ceil(summary.totalEvents / 12); batch++) {
    const expected = await (await request.get(`/api/overview?eventsPage=${batch}`)).json()
    if (batch > 1) await page.getByRole('button', { name: '较早动态' }).click()
    await expect(page.locator('.recent-events .event-ship').first()).toHaveText(expected.recentEvents[0].shipName)
    await expect(page.locator('.event-range')).toContainText(`/ ${summary.totalEvents}`)
    seen.push(...await page.locator('.event-ship').evaluateAll(elements => elements.map(element => element.getAttribute('aria-label')!)))
  }
  expect(seen.length).toBe(summary.totalEvents)
  expect(new Set(seen).size).toBeGreaterThan(5)
  await expect(page.getByRole('button', { name: '较早动态' })).toBeDisabled()
  const label = await page.locator('.event-ship').first().getAttribute('aria-label')
  await page.locator('.event-ship').first().click()
  await expect(page.locator('#appointment-detail')).toContainText(label!.split('预约 ')[1])
  await expect(page.locator('.appointments-pane tbody tr')).toHaveCount(20)
  await expect(page.locator('.appointments-pane .pagination')).toContainText('共 53 条预约')
})

