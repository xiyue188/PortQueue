test('候选总量、继续加载与全部结果一致，状态不会截断全局搜索', async ({ page, request }) => {
  const data = await (await request.get('/api/appointments?pageSize=100')).json()
  await page.goto('/#appointments')
  await page.getByRole('button', { name: '待审核', exact: true }).click()
  const input = page.getByRole('combobox', { name: '预约关键词' })
  await input.click()
  await expect(page.locator('.search-result-heading')).toHaveText(`共 ${data.totalCount} 条匹配预约`)
  await expect(page.locator('.search-option')).toHaveCount(6)
  await page.getByRole('button', { name: '加载更多', exact: true }).click()
  await expect(page.locator('.search-option')).toHaveCount(12)
  await expect(page.locator('.search-option').nth(6)).toContainText(data.items[6].appointmentNo)
  await page.getByRole('button', { name: '查看全部结果' }).click()
  await expect(page.locator('.appointments-pane tbody tr')).toHaveCount(20)
  await expect(page.locator('.appointments-pane .pagination')).toContainText(`共 ${data.totalCount} 条`)
  for (const keyword of [data.items[0].imoNo, data.items[0].mmsi].filter(Boolean)) {
    await input.fill(keyword)
    await input.click()
    const expected = await (await request.get(`/api/appointments?keyword=${keyword}`)).json()
    await expect(page.locator('.search-result-heading')).toHaveText(`共 ${expected.totalCount} 条匹配预约`)
    await expect(page.locator('.search-option').first()).toContainText(expected.items[0].shipName)
  }
})

test('加载候选失败可重试，新关键词不会被旧分页覆盖', async ({ page }) => {
  await page.goto('/')
  const input = page.getByRole('combobox', { name: '预约关键词' })
  await input.click()
  await expect(page.locator('.search-option')).toHaveCount(6)
  const nextBatch = (url: URL) => url.pathname === '/api/appointments' && url.searchParams.get('pageSize') === '6' && url.searchParams.get('page') === '2'
  await page.route(nextBatch, route => route.fulfill({ status: 503, body: '{}' }))
  await page.getByRole('button', { name: '加载更多', exact: true }).click()
  await expect(page.locator('.search-message[role=alert]')).toBeVisible()
  await expect(page.locator('.search-option')).toHaveCount(6)
  await page.unroute(nextBatch)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.locator('.search-option')).toHaveCount(12)
  let release: (() => void) | undefined
  let intercepted: (() => void) | undefined
  const held = new Promise<void>(resolve => { release = resolve })
  const started = new Promise<void>(resolve => { intercepted = resolve })
  await page.route(url => url.pathname === '/api/appointments' && url.searchParams.get('page') === '3' && url.searchParams.get('pageSize') === '6', async route => {
    const response = await route.fetch()
    intercepted?.(); await held
    await route.fulfill({ response }).catch(() => { /* 关键词变化会取消这次分页。 */ })
  })
  await page.getByRole('button', { name: '加载更多', exact: true }).click()
  await started
  await input.fill('海岚')
  await expect(page.locator('.search-option').first()).toContainText('海岚')
  release?.()
  const names = await page.locator('.search-option strong').allTextContents()
  expect(names.every(name => name.includes('海岚'))).toBeTruthy()
})

