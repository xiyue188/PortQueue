  await page.route(detailEndpoint, route => route.fulfill({ status: 503, body: '{}' }))
  await page.locator('.event-ship').first().click()
  await expect(page.locator('.detail-host [role=alert]')).toContainText('详情暂时无法读取')
  await expect(page.locator('.appointments-pane tbody tr')).toHaveCount(20)
  await page.unroute(detailEndpoint)
  await page.getByRole('button', { name: '重试详情' }).click()
  await expect(page.locator('#appointment-detail')).toContainText('PQ202611-1045')
  await page.getByRole('button', { name: '总览', exact: true }).click()
  let release: (() => void) | undefined
  let intercepted: (() => void) | undefined
  const held = new Promise<void>(resolve => { release = resolve })
  const started = new Promise<void>(resolve => { intercepted = resolve })
  await page.route(detailEndpoint, async route => {
    const response = await route.fetch()
    intercepted?.(); await held
    await route.fulfill({ response }).catch(() => { /* 后选记录已取消旧详情请求。 */ })
  })
  await page.locator('.event-ship').first().click()
  await started
  const row = page.locator('.appointments-pane .vessel-row').first()
  const rowNo = await row.locator('small').innerText()
  await row.click()
  release?.()
  await expect(page.locator('#appointment-detail')).toContainText(rowNo)
