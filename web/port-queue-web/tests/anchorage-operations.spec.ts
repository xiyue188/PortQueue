// 真库办理链路；仅“响应丢失”用网络故障注入，服务端仍执行真实事务。
import { test, expect } from '@playwright/test'
import { loginAnchorage as login } from './anchorage-support'
const local = (value: Date) => new Date(value.getTime() + 8*3600_000).toISOString().slice(0,19)
test('登记入锚、维护预计、丢失响应核对、离锚释放容量',async({page}) => {
  await login(page,'pq.dispatcher')
  const areas = await (await page.request.get('/api/anchorages')).json()
  const area = areas.items.find((a: {code:string})=>a.code === 'ANCH-INNER-A')
  expect(area).toBeTruthy()
  await page.getByRole('button',{name:new RegExp(area.name)}).click()
  await expect(page.locator('.aq-heading h2')).toHaveText(area.name)
  const initial = await (await page.request.get(`/api/anchorages/${area.anchorageId}/queue`)).json()
  await page.getByRole('button',{name:'登记入锚',exact:true}).click()
  const modal = page.locator('.aq-operation[open]')
  await expect(modal.locator('.aq-candidate input').first()).toBeVisible()
  const candidateSearch = modal.locator('#aq-candidate-search')
  let composingRequests = 0
  const countCandidates = (request: { url: () => string }) => { if (request.url().includes('/entry-candidates')) composingRequests++ }
  page.on('request',countCandidates)
  await candidateSearch.fill('jiang')
  await candidateSearch.dispatchEvent('compositionstart')
  await candidateSearch.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true,bubbles:true})
  await page.waitForTimeout(350)
  expect(composingRequests).toBe(0)
  await candidateSearch.fill('')
  await candidateSearch.dispatchEvent('compositionend')
  await expect.poll(()=>composingRequests).toBe(1)
  page.off('request',countCandidates)
  await expect(modal.locator('.aq-candidate input').first()).toBeVisible()
  await modal.locator('.aq-candidate input').first().check()
  await modal.locator('#aq-operation-time').fill(local(new Date()))
  await modal.locator('#aq-operation-reason').fill('第四阶段浏览器验收入锚')
  await modal.getByRole('button',{name:'确认保存'}).click()
  await expect(modal).toHaveCount(0)
  await expect(page.locator('.aq-feedback')).toContainText('已登记入锚')
  await expect(page.locator('.aq-occupancy strong')).toHaveText(String(initial.occupiedCount+1))
  await page.getByRole('button',{name:'关闭操作结果'}).click()
  const afterEntry = await (await page.request.get(`/api/anchorages/${area.anchorageId}/queue`)).json()
  const entered = afterEntry.items.find((item: {queueEntryId:string})=>!initial.items.some((old: {queueEntryId:string})=>old.queueEntryId === item.queueEntryId))
  expect(entered).toBeTruthy()
  await page.getByRole('button',{name:'人工预计靠泊'}).click()
  const estimate = new Date(Date.now()+3*3600_000)
  await modal.locator('#aq-operation-time').fill(local(estimate))
  await modal.locator('#aq-operation-reason').fill('按当前候泊情况预计三小时后靠泊')
  await modal.getByRole('button',{name:'确认保存'}).click()
  await expect(modal).toHaveCount(0)
  await expect(page.locator('.aq-feedback')).toContainText('已更新预计靠泊')
  let detail = await (await page.request.get(`/api/anchorage-stays/${entered.queueEntryId}`)).json()
  expect(Math.abs(Date.parse(detail.manualEstimatedBerthingAt)-estimate.getTime())).toBeLessThan(1000)
  expect(detail.estimateVersion).not.toBe('0')
  await page.getByRole('button',{name:'关闭操作结果'}).click()
  // 提交后主动丢失响应：页面必须核对，不能重发同一次写入。
  let writes = 0
  await page.route(`**/api/anchorage-stays/${entered.queueEntryId}/estimate`,async route=>{
    if (route.request().method() !== 'PUT') return route.continue()
    writes++; const response = await route.fetch(); expect(response.ok()).toBeTruthy(); await route.abort('failed')
  })
  await page.getByRole('button',{name:'人工预计靠泊'}).click()
  await modal.getByRole('button',{name:'清除预计'}).click()
  await modal.locator('#aq-operation-reason').fill('响应丢失核对验收：清除人工预计')
  await modal.getByRole('button',{name:'确认保存'}).click()
  await expect(modal).toContainText('尚未确认保存结果')
  await expect(modal.getByRole('button',{name:'确认保存'})).toHaveCount(0)
  await modal.getByRole('button',{name:'稍后核对'}).click()
  await expect(modal).toHaveCount(0)
  await page.getByRole('button',{name:'核对原操作'}).click()
  await modal.getByRole('button',{name:'读取最新记录'}).click()
  await expect(modal).toContainText('已读到与原操作一致的记录')
  expect(writes).toBe(1)
  await modal.getByRole('button',{name:'结束核对'}).click()
  await page.unroute(`**/api/anchorage-stays/${entered.queueEntryId}/estimate`)
  await page.getByRole('button',{name:'登记离锚',exact:true}).click()
  await modal.locator('#aq-operation-time').fill(local(new Date()))
  await modal.locator('#aq-operation-reason').fill('第四阶段浏览器验收离锚')
  await modal.getByRole('button',{name:'确认保存'}).click()
  await expect(modal).toHaveCount(0)
  await expect(page.locator('.aq-occupancy strong')).toHaveText(String(initial.occupiedCount))
  await expect(page.locator('.aq-state')).toHaveText('已离锚')
  detail = await (await page.request.get(`/api/anchorage-stays/${entered.queueEntryId}`)).json()
  expect(detail.events.filter((event: {queueEntryId:string})=>event.queueEntryId===entered.queueEntryId)).toHaveLength(2)
  expect(detail.manualEstimatedBerthingAt).toBeNull()
  expect(Date.parse(detail.leftAt)).toBeGreaterThanOrEqual(Date.parse(detail.enteredAt))
})

